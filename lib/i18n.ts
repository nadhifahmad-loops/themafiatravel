export type Lang = 'ID' | 'EN';

/**
 * Isi placeholder `{nama}` pada template terjemahan.
 * Contoh: tpl('Menampilkan {count} hasil', { count: 12 }) → 'Menampilkan 12 hasil'
 */
export function tpl(
  template: string,
  vars: Record<string, string | number>
): string {
  return template.replace(/\{(\w+)\}/g, (match, key: string) =>
    key in vars ? String(vars[key]) : match
  );
}
